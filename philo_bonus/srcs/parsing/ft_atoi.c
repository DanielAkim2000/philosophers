#include "../../includes/parsing_bonus.h"

int	ft_atoi(const char *s)
{
	int	i;
	int	r;

	i = 0;
	r = 0;
	while (s[i] >= '0' && s[i] <= '9')
		r = r * 10 + (s[i++] - '0');
	return (r);
}
