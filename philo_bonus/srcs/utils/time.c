#include "../../includes/utils_bonus.h"

long	ft_get_time(void)
{
	struct timeval	tv;

	gettimeofday(&tv, NULL);
	return (tv.tv_sec * 1000 + tv.tv_usec / 1000);
}

void	ft_sleep(long ms)
{
	long	start;

	start = ft_get_time();
	while (ft_get_time() - start < ms)
		usleep(500);
}
